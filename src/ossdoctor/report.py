"""Rendering a :class:`~ossdoctor.runner.Report` as text, Markdown or JSON."""

from __future__ import annotations

import json
import os
import sys
from typing import TextIO

from . import __version__
from .checks import CATEGORIES, Status
from .runner import Report

_SYMBOLS = {Status.PASS: "✔", Status.FAIL: "✘", Status.SKIP: "–"}
_ASCII = {Status.PASS: "ok", Status.FAIL: "!!", Status.SKIP: "--"}
_COLORS = {Status.PASS: "32", Status.FAIL: "31", Status.SKIP: "90"}
_EMOJI = {Status.PASS: "✅", Status.FAIL: "❌", Status.SKIP: "⏭️"}


def use_color(stream: TextIO) -> bool:
    if os.environ.get("NO_COLOR"):
        return False
    if os.environ.get("FORCE_COLOR"):
        return True
    return hasattr(stream, "isatty") and stream.isatty()


def _supports_unicode(stream: TextIO) -> bool:
    try:
        "✔✘–".encode(getattr(stream, "encoding", None) or "ascii")
    except (UnicodeEncodeError, LookupError):
        return False
    return True


def render_text(report: Report, stream: TextIO = sys.stdout, verbose: bool = False) -> str:
    color = use_color(stream)
    symbols = _SYMBOLS if _supports_unicode(stream) else _ASCII

    def paint(text: str, code: str) -> str:
        return f"\033[{code}m{text}\033[0m" if color else text

    width = max((len(r.check.title) for r in report.results), default=0)
    out = [paint(f"ossdoctor {__version__}", "1") + f"  {report.repo.root}", ""]
    for category in CATEGORIES:
        rows = [r for r in report.results if r.check.category == category]
        if not rows:
            continue
        out.append(paint(category, "1"))
        for r in rows:
            mark = paint(symbols[r.status], _COLORS[r.status])
            out.append(f"  {mark} {r.check.title.ljust(width)}  {paint(r.outcome.detail, '90')}")
            if r.status is Status.FAIL and verbose:
                out.append(f"      {r.check.hint}")
        out.append("")

    fails = report.by_status(Status.FAIL)
    score = report.score
    score_color = "32" if score >= 90 else "33" if score >= 60 else "31"
    out.append(
        paint(f"Score: {score}/100", "1;" + score_color)
        + f"  ({len(report.by_status(Status.PASS))} passed, {len(fails)} failed, {len(report.by_status(Status.SKIP))} skipped)"
    )
    if fails and not verbose:
        out.append("Run with --verbose to see how to fix each failure.")
    if report.fixable:
        out.append(f"`ossdoctor fix` can generate files for {len(report.fixable)} failing check(s).")
    return "\n".join(out) + "\n"


def render_markdown(report: Report) -> str:
    out = [
        f"## ossdoctor report: {report.score}/100",
        "",
        "| | Check | Level | Details |",
        "|---|---|---|---|",
    ]
    for r in report.results:
        detail = r.outcome.detail.replace("|", "\\|")
        out.append(f"| {_EMOJI[r.status]} | {r.check.title} | {r.check.level.value} | {detail} |")
    fails = report.by_status(Status.FAIL)
    if fails:
        out += ["", "### How to fix", ""]
        out += [f"- **{r.check.title}** (`{r.check.id}`): {r.check.hint}" for r in fails]
    if report.fixable:
        out += ["", f"Run `ossdoctor fix` locally to generate files for {len(report.fixable)} of these."]
    out += ["", f"<sub>Generated by [ossdoctor](https://pypi.org/project/ossdoctor/) {__version__}</sub>"]
    return "\n".join(out) + "\n"


def report_to_dict(report: Report) -> dict:
    return {
        "version": __version__,
        "path": str(report.repo.root),
        "score": report.score,
        "summary": {s.value: len(report.by_status(s)) for s in Status},
        "results": [
            {
                "id": r.check.id,
                "title": r.check.title,
                "category": r.check.category,
                "level": r.check.level.value,
                "status": r.status.value,
                "detail": r.outcome.detail,
                "hint": r.check.hint,
                "fixable": r.check.fixable,
            }
            for r in report.results
        ],
    }


def render_json(report: Report) -> str:
    return json.dumps(report_to_dict(report), indent=2, ensure_ascii=False) + "\n"
